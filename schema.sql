-- Run this in Supabase SQL Editor.
create table if not exists public.room_messages (
  id bigint generated by default as identity primary key,
  room_id text not null check (room_id ~ '^[A-Z0-9_-]{2,24}$'),
  nickname text not null check (char_length(nickname) between 1 and 24),
  message text not null check (char_length(message) between 1 and 240),
  created_at timestamptz not null default now()
);

create index if not exists room_messages_room_id_id_idx
  on public.room_messages (room_id, id);

-- The Netlify function uses the Supabase service_role key server-side.
-- Disable direct anonymous table access; clients must go through Netlify.
alter table public.room_messages enable row level security;

revoke all on table public.room_messages from anon, authenticated;
-- Do not add a public policy for this table.
